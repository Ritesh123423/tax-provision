  /* ══════════════════════════════════════
     SHEET 3 — DEFERRED TAX
  ══════════════════════════════════════ */
  function addDeferredTaxSheet(WB, dt){
    const rate = v('ci-rate');
    const rows = [
      [FIRM],
      ['DEFERRED TAX SCHEDULE — Ind AS 12 (Balance Sheet Approach)'],
      ['Client: '+s('ci-name')+'  |  FY: '+s('ci-fy')+'  |  Tax Rate: '+rate.toFixed(3)+'%'],
      ['Note: Temp Diff = Carrying Amount (Ind AS) − Tax Base (Income Tax Act, 1961)'],
      [''],
      ['SECTION A — ASSETS'],
      ['For Assets: CA > Tax Base → Taxable Temp. Difference → DTL  |  CA < Tax Base → Deductible Temp. Difference → DTA'],
      ['SR','PARTICULARS','CARRYING AMT (₹)','TAX BASE (₹)','TEMP DIFF (₹)','NATURE','TAX EFFECT (₹)','NOTES'],
    ];

    let aTotalDTA=0, aTotalDTL=0;
    dt.assetRows.forEach((r,i)=>{
      rows.push([i+1,r.label,fmt(r.ca),fmt(r.tb),fmt(r.diff),r.nature,fmt(r.te),r.note||'']);
      if(r.nature==='DTA') aTotalDTA+=r.te; else if(r.nature==='DTL') aTotalDTL+=r.te;
    });
    rows.push(['','SUBTOTAL — ASSETS','','','','DTA',fmt(aTotalDTA),'']);
    rows.push(['','','','','','DTL',fmt(aTotalDTL),'']);

    rows.push([''],
    ['SECTION B — LIABILITIES & PROVISIONS'],
    ['For Liabilities: CA > Tax Base → Deductible Temp. Difference → DTA  |  CA < Tax Base → Taxable Temp. Difference → DTL'],
    ['SR','PARTICULARS','CARRYING AMT (₹)','TAX BASE (₹)','TEMP DIFF (₹)','NATURE','TAX EFFECT (₹)','NOTES']);

    let lTotalDTA=0, lTotalDTL=0;
    dt.liabRows.forEach((r,i)=>{
      rows.push([i+1,r.label,fmt(r.ca),fmt(r.tb),fmt(r.diff),r.nature,fmt(r.te),r.note||'']);
      if(r.nature==='DTA') lTotalDTA+=r.te; else if(r.nature==='DTL') lTotalDTL+=r.te;
    });
    rows.push(['','SUBTOTAL — LIABILITIES','','','','DTA',fmt(lTotalDTA),'']);
    rows.push(['','','','','','DTL',fmt(lTotalDTL),'']);

    rows.push([''],
    ['SECTION C — OTHER DEFERRED ITEMS (Losses / MAT Credit)'],
    ['SR','PARTICULARS','BASE AMOUNT (₹)','','','TYPE','TAX EFFECT (₹)','NOTES']);
    let oTotalDTA=0, oTotalDTL=0;
    dt.otherRows.forEach((r,i)=>{
      rows.push([i+1,r.label,fmt(r.amt),'','',r.type.toUpperCase(),fmt(r.te),r.note||'']);
      if(r.type==='dta') oTotalDTA+=r.te; else oTotalDTL+=r.te;
    });

    rows.push([''],
    ['CONSOLIDATED DEFERRED TAX POSITION'],
    ['','Gross Deferred Tax Asset (DTA)','','',' ',fmt(dt.grossDTA),'',''],
    ['','Gross Deferred Tax Liability (DTL)','','',' ',fmt(dt.grossDTL),'',''],
    ['','Net DTA / (DTL)','','','',fmt(dt.grossDTA-dt.grossDTL),'',''],
    ['','Deferred Tax P&L Impact (Charge) / Credit','','','',fmt(dt.dtPLCharge),'','']);

    const WS = XLSX.utils.aoa_to_sheet(rows);
    WS['!cols']=[{wch:6},{wch:52},{wch:18},{wch:18},{wch:16},{wch:8},{wch:16},{wch:40}];
    XLSX.utils.book_append_sheet(WB, WS, 'DT');
  }

