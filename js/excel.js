  /* ══════════════════════════════════════
     MASTER EXPORT FUNCTION
  ══════════════════════════════════════ */
  async function exportWorkpaper(){
    UI.toast('Generating Excel workpaper…','info',3000);

    /* Load SheetJS from CDN */
    if(!window.XLSX){
      try{
        await loadScript('https://cdnjs.cloudflare.com/ajax/libs/xlsx/0.18.5/xlsx.full.min.js');
      } catch(e){
        UI.toast('Could not load Excel library. Check internet connection.','err');
        return;
      }
    }

    const result = getResult();
    if(!result){ UI.toast('Please compute first.','err'); return; }
    const { ct, dt, total, etr } = result;

    const WB = XLSX.utils.book_new();
    WB.Props = { Title: TOOL, Author: FIRM, CreatedDate: new Date() };

    /* ── SHEET 1: Cover / Index ── */
    addCoverSheet(WB, ct, dt, total, etr);

    /* ── SHEET 2: Current Tax ── */
    addCurrentTaxSheet(WB, ct);

    /* ── SHEET 3: Deferred Tax Schedule ── */
    addDeferredTaxSheet(WB, dt);

    /* ── SHEET 4: DTA-DTL Movement ── */
    addMovementSheet(WB, dt);

    /* ── SHEET 5: Journal Entries ── */
    addJESheet(WB, ct, dt);

    /* ── SHEET 6: Disclosure Note ── */
    addDisclosureSheet(WB, ct, dt, total, etr);

    /* ── SHEET 7: ETR Reconciliation ── */
    addETRSheet(WB, ct, dt, total, etr);

    /* ── SHEET 8: Auditor Checklist ── */
    addChecklistSheet(WB);

    /* Download */
    const client = s('ci-name').replace(/\s+/g,'_')||'Client';
    const fy     = s('ci-fy').replace(/[^0-9-]/g,'')||'FY';
    const fname  = `KGS_TaxProvision_${client}_${fy}.xlsx`;
    XLSX.writeFile(WB, fname);
    UI.toast('Excel workpaper downloaded ✓','ok');
  }

